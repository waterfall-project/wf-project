"""The correlation of an example of an error of the contract, derived from its name (#1007).

An example of an error — one whose value is the envelope of an error, with its ``correlation_id``
— is named by its file under ``fixtures/api/``, without ``.json``. Its correlation is the prefix of
the universe, then the first twelve hexadecimal digits of the SHA-256 of that name: two lots drawn
from the same branch of an epic cannot give the same one without giving the same name, which two
files cannot have. The next number free in a range, seen from the base of each branch, was taken
twice by two lots in parallel, and renumbered when the epic took them in (#1007).

The examples of errors numbered before the rule keep their numbers, in the ranges of the
correlations of ``wftools.mockids``: their names are frozen here, those of ``main`` and of the
branches of the epics in progress when the rule was written, some of which reach this branch only
when it takes those in (``tests/test_mockcorrelations.py``). One numbered by hand since on a branch
of an epic drawn before the rule joins them when it is taken in, with its number; no other does.
"""

import hashlib

from wftools.mockids import PREFIX

DIGITS = 12
"""The hexadecimal digits of the digest that follow the prefix: the last group of a UUID."""


def correlation(name: str) -> str:
    """Return the correlation of an example of an error, from the name of its file."""
    return PREFIX + hashlib.sha256(name.encode()).hexdigest()[:DIGITS]


